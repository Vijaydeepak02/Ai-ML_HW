##Perform addition, subtraction, multiplication, and division on NumPy arrays.##

import numpy as np

arr = np.array([10, 20, 30, 40, 50])

print("Original Array:")
print(arr)

print("\nAddition:")
print(arr + 5)

print("\nSubtraction:")
print(arr - 5)

print("\nMultiplication:")
print(arr * 2)

print("\nDivision:")
print(arr / 2)